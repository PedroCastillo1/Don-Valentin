-- Don Valentín Digital · Modelo de datos unificado (H2, 16/10/2026)
-- Motor: PostgreSQL 17 (Supabase en el ambiente de prueba; misma versión en las pruebas locales).
-- Antes era MySQL 8.4: se pasó a PostgreSQL el 16/10/2026 al elegir Supabase (decisión del equipo, supuesto S-03).
-- Entidades del alcance (Declaración del Alcance v4 §1.6): cliente, reserva, franja, sector, mesa, sesión de mesa,
-- pedido, ítem del pedido, producto de la carta, tipo de solicitud, usuario, rol y estado.
-- «estado» se modela como columna con CHECK en cada entidad que lo tiene.
-- Las tablas de pedidos (H4, 06/11/2026) existen para que el modelo sea único, pero ningún módulo las usa todavía.
-- Fechas y horas: timestamptz (instante) y date (día de servicio). Banderas: smallint 0/1.

-- ───────── Usuarios, roles y auditoría (RNF-3) ─────────
CREATE TABLE roles (
  id          smallint     PRIMARY KEY,
  codigo      varchar(20)  NOT NULL UNIQUE,
  nombre      varchar(60)  NOT NULL,
  descripcion varchar(255) NOT NULL
);

CREATE TABLE usuarios (
  id                integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario           varchar(40)  NOT NULL UNIQUE,
  nombre            varchar(80)  NOT NULL,
  rol_id            smallint     NOT NULL REFERENCES roles (id),
  password_hash     varchar(255) NOT NULL,
  activo            smallint     NOT NULL DEFAULT 1 CHECK (activo IN (0, 1)),
  intentos_fallidos smallint     NOT NULL DEFAULT 0,
  bloqueado_hasta   timestamptz(3) NULL,
  ultimo_acceso     timestamptz(3) NULL,
  creado_en         timestamptz(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  actualizado_en    timestamptz(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3)
);

CREATE TABLE sesiones_usuario (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  token_hash  char(64)     NOT NULL UNIQUE,
  csrf_token  char(43)     NOT NULL,
  usuario_id  integer      NOT NULL REFERENCES usuarios (id) ON DELETE CASCADE,
  creada_en   timestamptz(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  expira_en   timestamptz(3) NOT NULL,
  ip          varchar(45)  NULL,
  user_agent  varchar(255) NULL
);
CREATE INDEX ix_sesiones_usuario ON sesiones_usuario (usuario_id);
CREATE INDEX ix_sesiones_expira ON sesiones_usuario (expira_en);

CREATE TABLE auditoria (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id integer      NULL REFERENCES usuarios (id) ON DELETE SET NULL,
  accion     varchar(60)  NOT NULL,
  recurso    varchar(160) NOT NULL,
  resultado  varchar(10)  NOT NULL CHECK (resultado IN ('permitido', 'denegado', 'error')),
  detalle    jsonb        NULL,
  ip         varchar(45)  NULL,
  creada_en  timestamptz(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3)
);
CREATE INDEX ix_auditoria_fecha ON auditoria (creada_en);
CREATE INDEX ix_auditoria_resultado ON auditoria (resultado, creada_en);

-- ───────── Salón: sectores, mesas, franjas y aforo ─────────
CREATE TABLE sectores_salon (
  id                smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo            varchar(30) NOT NULL UNIQUE,
  nombre            varchar(60) NOT NULL,
  activo            smallint    NOT NULL DEFAULT 1 CHECK (activo IN (0, 1)),
  estado_validacion varchar(12) NOT NULL DEFAULT 'provisorio' CHECK (estado_validacion IN ('documentado', 'provisorio', 'validado'))
);

CREATE TABLE sectores_preparacion (
  id     smallint    PRIMARY KEY,
  codigo varchar(10) NOT NULL UNIQUE CHECK (codigo IN ('cocina', 'parrilla', 'barra')),
  nombre varchar(40) NOT NULL
);

CREATE TABLE mesas (
  id                smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  numero            smallint    NOT NULL UNIQUE CHECK (numero BETWEEN 1 AND 999),
  sector_salon_id   smallint    NOT NULL REFERENCES sectores_salon (id),
  capacidad         smallint    NOT NULL CHECK (capacidad BETWEEN 1 AND 40),
  activa            smallint    NOT NULL DEFAULT 1 CHECK (activa IN (0, 1)),
  qr_token          char(32)    NOT NULL UNIQUE,
  qr_generado_en    timestamptz(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  estado_validacion varchar(12) NOT NULL DEFAULT 'provisorio' CHECK (estado_validacion IN ('documentado', 'provisorio', 'validado'))
);

CREATE TABLE franjas (
  id                smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo            varchar(20) NOT NULL UNIQUE,
  nombre            varchar(40) NOT NULL,
  hora_inicio       time        NOT NULL,
  duracion_min      smallint    NOT NULL CHECK (duracion_min BETWEEN 15 AND 360),
  orden             smallint    NOT NULL UNIQUE,
  activa            smallint    NOT NULL DEFAULT 1 CHECK (activa IN (0, 1)),
  estado_validacion varchar(12) NOT NULL DEFAULT 'provisorio' CHECK (estado_validacion IN ('documentado', 'provisorio', 'validado'))
);

CREATE TABLE aforos (
  franja_id         smallint    NOT NULL REFERENCES franjas (id) ON DELETE CASCADE,
  sector_salon_id   smallint    NOT NULL REFERENCES sectores_salon (id),
  aforo_personas    smallint    NOT NULL CHECK (aforo_personas >= 0),
  estado_validacion varchar(12) NOT NULL DEFAULT 'provisorio' CHECK (estado_validacion IN ('documentado', 'provisorio', 'validado')),
  PRIMARY KEY (franja_id, sector_salon_id)
);

CREATE TABLE parametros (
  clave             varchar(60)  PRIMARY KEY,
  valor             varchar(255) NOT NULL,
  tipo              varchar(10)  NOT NULL CHECK (tipo IN ('entero', 'texto', 'booleano')),
  unidad            varchar(20)  NULL,
  descripcion       varchar(255) NOT NULL,
  fuente            varchar(255) NOT NULL,
  estado_validacion varchar(12)  NOT NULL CHECK (estado_validacion IN ('documentado', 'provisorio', 'validado')),
  actualizado_en    timestamptz(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  actualizado_por   integer      NULL REFERENCES usuarios (id) ON DELETE SET NULL
);

-- ───────── Clientes y reservas (RF-R1, RF-R2; RNF-4: solo nombre y teléfono) ─────────
CREATE TABLE clientes (
  id        integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre    varchar(80) NOT NULL,
  telefono  varchar(15) NOT NULL UNIQUE,
  creado_en timestamptz(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3)
);

CREATE TABLE reservas (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo          char(8)      NOT NULL UNIQUE,
  fecha_servicio  date         NOT NULL,
  franja_id       smallint     NOT NULL REFERENCES franjas (id),
  sector_salon_id smallint     NOT NULL REFERENCES sectores_salon (id),
  mesa_id         smallint     NOT NULL REFERENCES mesas (id),
  cliente_id      integer      NOT NULL REFERENCES clientes (id),
  a_nombre_de     varchar(80)  NOT NULL,
  personas        smallint     NOT NULL CHECK (personas BETWEEN 1 AND 40),
  estado          varchar(10)  NOT NULL DEFAULT 'confirmada' CHECK (estado IN ('confirmada', 'cancelada', 'no_show', 'cumplida')),
  origen          varchar(10)  NOT NULL CHECK (origen IN ('web', 'telefono', 'presencial')),
  comentarios     varchar(300) NULL,
  creada_por      integer      NULL REFERENCES usuarios (id) ON DELETE SET NULL,
  creada_en       timestamptz(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  actualizada_en  timestamptz(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3)
);
-- Una mesa no puede tener dos reservas confirmadas en la misma franja del mismo día (garantía en la base).
CREATE UNIQUE INDEX uq_reservas_mesa_franja ON reservas (mesa_id, fecha_servicio, franja_id) WHERE estado = 'confirmada';
CREATE INDEX ix_reservas_dia ON reservas (fecha_servicio, franja_id, estado);
CREATE INDEX ix_reservas_cliente ON reservas (cliente_id);

-- Contador por (día, franja, sector): fila que se bloquea para que dos reservas simultáneas no superen el aforo (KQ-5).
CREATE TABLE ocupacion_franja (
  fecha_servicio       date     NOT NULL,
  franja_id            smallint NOT NULL REFERENCES franjas (id),
  sector_salon_id      smallint NOT NULL REFERENCES sectores_salon (id),
  personas_confirmadas smallint NOT NULL DEFAULT 0 CHECK (personas_confirmadas >= 0),
  PRIMARY KEY (fecha_servicio, franja_id, sector_salon_id)
);

-- ───────── Sesión de mesa (apertura por mozo o por reserva; base del circuito QR) ─────────
CREATE TABLE sesiones_mesa (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  mesa_id     smallint    NOT NULL REFERENCES mesas (id),
  reserva_id  bigint      NULL REFERENCES reservas (id) ON DELETE SET NULL,
  abierta_por integer     NULL REFERENCES usuarios (id) ON DELETE SET NULL,
  estado      varchar(8)  NOT NULL DEFAULT 'abierta' CHECK (estado IN ('abierta', 'cerrada')),
  abierta_en  timestamptz(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  cerrada_en  timestamptz(3) NULL
);
-- Dos mozos que abren a la vez la misma mesa generan una única sesión.
CREATE UNIQUE INDEX uq_sesion_mesa_abierta ON sesiones_mesa (mesa_id) WHERE estado = 'abierta';

-- ───────── Carta, tipos de solicitud y pedidos (carta pública: RF-W1; pedidos: H4) ─────────
CREATE TABLE tipos_solicitud (
  id                    smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sector_preparacion_id smallint    NOT NULL REFERENCES sectores_preparacion (id),
  codigo                varchar(40) NOT NULL UNIQUE,
  nombre                varchar(80) NOT NULL,
  tiempo_maximo_min     smallint    NOT NULL CHECK (tiempo_maximo_min BETWEEN 1 AND 240),
  estado_validacion     varchar(12) NOT NULL DEFAULT 'provisorio' CHECK (estado_validacion IN ('documentado', 'provisorio', 'validado'))
);

CREATE TABLE categorias_carta (
  id     smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo varchar(40) NOT NULL UNIQUE,
  nombre varchar(80) NOT NULL,
  grupo  varchar(60) NOT NULL,
  orden  smallint    NOT NULL
);

CREATE TABLE productos (
  id                    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  categoria_id          smallint     NOT NULL REFERENCES categorias_carta (id),
  sector_preparacion_id smallint     NOT NULL REFERENCES sectores_preparacion (id),
  tipo_solicitud_id     smallint     NOT NULL REFERENCES tipos_solicitud (id),
  nombre                varchar(120) NOT NULL,
  nota                  varchar(255) NULL,
  sin_tacc              smallint     NOT NULL DEFAULT 0 CHECK (sin_tacc IN (0, 1)),
  disponible            smallint     NOT NULL DEFAULT 1 CHECK (disponible IN (0, 1)),
  orden                 smallint     NOT NULL
);
CREATE INDEX ix_productos_categoria ON productos (categoria_id, orden);

CREATE TABLE variantes_producto (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  producto_id integer     NOT NULL REFERENCES productos (id) ON DELETE CASCADE,
  etiqueta    varchar(40) NOT NULL,
  -- NULL cuando la carta impresa no permite leer el importe; lo confirma el local.
  precio      numeric(10, 2) NULL,
  orden       smallint    NOT NULL,
  UNIQUE (producto_id, etiqueta)
);

CREATE TABLE pedidos (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sesion_mesa_id bigint      NOT NULL REFERENCES sesiones_mesa (id),
  origen         varchar(4)  NOT NULL CHECK (origen IN ('qr', 'mozo')),
  estado         varchar(15) NOT NULL DEFAULT 'recibido' CHECK (estado IN ('recibido', 'en_preparacion', 'listo', 'entregado', 'cancelado')),
  creado_en      timestamptz(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  actualizado_en timestamptz(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3)
);
CREATE INDEX ix_pedidos_sesion ON pedidos (sesion_mesa_id);

CREATE TABLE pedido_items (
  id                    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pedido_id             bigint      NOT NULL REFERENCES pedidos (id) ON DELETE CASCADE,
  variante_id           integer     NOT NULL REFERENCES variantes_producto (id),
  sector_preparacion_id smallint    NOT NULL REFERENCES sectores_preparacion (id),
  cantidad              smallint    NOT NULL CHECK (cantidad BETWEEN 1 AND 50),
  precio_unitario       numeric(10, 2) NOT NULL,
  estado                varchar(15) NOT NULL DEFAULT 'recibido' CHECK (estado IN ('recibido', 'en_preparacion', 'listo', 'entregado', 'cancelado')),
  listo_en              timestamptz(3) NULL
);
CREATE INDEX ix_items_sector ON pedido_items (sector_preparacion_id, estado);

-- ───────── "actualizado_en" se mueve solo en cada UPDATE (lo que en MySQL hacía ON UPDATE CURRENT_TIMESTAMP) ─────────
CREATE FUNCTION tocar_actualizado() RETURNS trigger LANGUAGE plpgsql SET search_path = '' AS $$
BEGIN
  NEW.actualizado_en := CURRENT_TIMESTAMP(3);
  RETURN NEW;
END $$;
CREATE FUNCTION tocar_actualizada() RETURNS trigger LANGUAGE plpgsql SET search_path = '' AS $$
BEGIN
  NEW.actualizada_en := CURRENT_TIMESTAMP(3);
  RETURN NEW;
END $$;
CREATE TRIGGER tg_usuarios_actualizado BEFORE UPDATE ON usuarios FOR EACH ROW EXECUTE FUNCTION tocar_actualizado();
CREATE TRIGGER tg_parametros_actualizado BEFORE UPDATE ON parametros FOR EACH ROW EXECUTE FUNCTION tocar_actualizado();
CREATE TRIGGER tg_pedidos_actualizado BEFORE UPDATE ON pedidos FOR EACH ROW EXECUTE FUNCTION tocar_actualizado();
CREATE TRIGGER tg_reservas_actualizada BEFORE UPDATE ON reservas FOR EACH ROW EXECUTE FUNCTION tocar_actualizada();

-- ───────── Seguridad en Supabase ─────────
-- El sistema entra a la base solo desde su API (usuario dueño de las tablas). Supabase además publica las tablas del
-- esquema public por su API REST con una llave pública: activamos RLS sin políticas para que por ese camino
-- no se pueda leer ni escribir nada. Fuera de Supabase (pruebas locales) esto no cambia nada.
DO $$
DECLARE t text;
BEGIN
  FOREACH t IN ARRAY ARRAY['roles','usuarios','sesiones_usuario','auditoria','sectores_salon','sectores_preparacion',
    'mesas','franjas','aforos','parametros','clientes','reservas','ocupacion_franja','sesiones_mesa',
    'tipos_solicitud','categorias_carta','productos','variantes_producto','pedidos','pedido_items']
  LOOP
    EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY', t);
  END LOOP;
END $$;
